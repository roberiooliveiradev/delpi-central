def _entry(
    *,
    method_id: str,
    name: str,
    purpose: str,
    kind: str,
    when_to_use: tuple[str, ...],
    when_not_to_use: tuple[str, ...],
    required_inputs: tuple[str, ...],
    questions: tuple[str, ...],
    steps: tuple[str, ...],
    outputs: tuple[str, ...],
    common_mistakes: tuple[str, ...],
    mapping_focus: tuple[str, ...],
    example: str,
    limitations: tuple[str, ...],
) -> dict[str, Any]:
    item = _playbook(
        method_id=method_id,
        name=name,
        purpose=purpose,
        when_to_use=when_to_use,
        when_not_to_use=when_not_to_use,
        required_inputs=required_inputs,
        questions=questions,
        steps=steps,
        outputs=outputs,
        common_mistakes=common_mistakes,
        mapping_focus=mapping_focus,
        source_section=_SOURCE,
    )
    item["family"] = "lean_six_sigma"
    item["kind"] = kind
    item["example"] = example
    item["limitations"] = list(limitations)
    item["computes_statistics"] = False
    item["certifies"] = False
    return item


def _sem(
    *,
    intents: tuple[str, ...] = (),
    minimum: tuple[dict[str, Any], ...] = (),
    favored_all: tuple[str, ...] = (),
    favored_any: tuple[str, ...] = (),
    disfavored: tuple[str, ...] = (),
    constraints: tuple[str, ...],
    stop_when: tuple[str, ...],
    not_sufficient: tuple[str, ...],
    gaps: tuple[dict[str, Any], ...] = (),
) -> dict[str, Any]:
    return {
        "intents": intents,
        "minimum_information": list(minimum),
        "favored_all": favored_all,
        "favored_any": favored_any,
        "disfavored_when": disfavored,
        "epistemic_constraints": constraints,
        "sufficiency": {
            "stop_when": stop_when,
            "not_sufficient_when": not_sufficient,
        },
        "gap_questions": gaps,
    }


def _gap(fact: str, text: str) -> dict[str, Any]:
    return {
        "id": f"gap_{fact}",
        "text": text,
        "kind": "readiness",
        "resolves": fact,
    }


def _req(fact: str, *accepts: str) -> dict[str, Any]:
    return {"fact": fact, "accepts": list(accepts) or ["yes"]}


