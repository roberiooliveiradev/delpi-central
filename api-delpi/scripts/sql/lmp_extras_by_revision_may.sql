-- Por revisão: minutos eng + homolog — extras sem pasta
WITH
TargetOvs AS (
    SELECT * FROM (VALUES ('000087','02'),('000102','02'),('003561','01'),('002871','01')) AS T(s,n)
),
EngSupport AS (
    SELECT * FROM (VALUES
        ('000002','000003'),('000002','000008'),('000002','000012'),
        ('000003','000003'),('000003','000012')
    ) AS E(p,st)
),
Ad1 AS (
    SELECT AD1.AD1_FILIAL, AD1.AD1_NROPOR, AD1.AD1_REVISA, RTRIM(AD1.AD1_DESCRI) AS descr
    FROM AD1010 AD1 INNER JOIN TargetOvs T ON T.s=AD1.AD1_NROPOR AND T.n=AD1.AD1_FILIAL
    WHERE AD1.D_E_L_E_T_=''
),
RevEng AS (
    SELECT A.AIJ_FILIAL, A.AIJ_NROPOR, A.AIJ_REVISA,
        MIN(A.AIJ_DTINIC) AS rev_first_eng,
        SUM(CASE WHEN ISNULL(A.AIJ_DTINIC,'')<>'' AND ISNULL(A.AIJ_HRINIC,'')<>'' AND ISNULL(A.AIJ_DTENCE,'')<>'' AND ISNULL(A.AIJ_HRENCE,'')<>''
            THEN DATEDIFF(MINUTE,
                CAST(CONCAT(SUBSTRING(A.AIJ_DTINIC,1,4),'-',SUBSTRING(A.AIJ_DTINIC,5,2),'-',SUBSTRING(A.AIJ_DTINIC,7,2),' ',A.AIJ_HRINIC,':00') AS DATETIME),
                CAST(CONCAT(SUBSTRING(A.AIJ_DTENCE,1,4),'-',SUBSTRING(A.AIJ_DTENCE,5,2),'-',SUBSTRING(A.AIJ_DTENCE,7,2),' ',A.AIJ_HRENCE,':00') AS DATETIME))
            ELSE 0 END) AS rev_min_closed,
        MAX(CASE WHEN (A.AIJ_PROVEN='000002' AND A.AIJ_STAGE='000012') OR (A.AIJ_PROVEN='000003' AND A.AIJ_STAGE='000012') THEN A.AIJ_DTINIC END) AS homolog_date,
        MAX(CASE WHEN (A.AIJ_PROVEN='000002' AND A.AIJ_STAGE='000008') OR (A.AIJ_PROVEN='000003' AND A.AIJ_STAGE IN ('000002','000008')) THEN 1 ELSE 0 END) AS has_sample
    FROM AIJ010 A
    INNER JOIN EngSupport E ON E.p=A.AIJ_PROVEN AND E.st=A.AIJ_STAGE
    WHERE A.D_E_L_E_T_='' AND EXISTS (SELECT 1 FROM TargetOvs T WHERE T.s=A.AIJ_NROPOR AND T.n=A.AIJ_FILIAL)
    GROUP BY A.AIJ_FILIAL, A.AIJ_NROPOR, A.AIJ_REVISA
)
SELECT
    R.AIJ_NROPOR AS sale_number,
    RTRIM(R.AIJ_FILIAL) AS branch,
    R.AIJ_REVISA AS revision,
    R.rev_first_eng,
    R.rev_min_closed,
    R.homolog_date,
    R.has_sample,
    CASE WHEN R.rev_first_eng BETWEEN '20260501' AND '20260531' THEN 1 ELSE 0 END AS eng_in_may,
    CASE WHEN R.rev_first_eng BETWEEN '20260401' AND '20260430' THEN 1 ELSE 0 END AS eng_in_apr,
    CASE WHEN R.homolog_date BETWEEN '20260501' AND '20260531' THEN 1 ELSE 0 END AS homolog_in_may
FROM RevEng R
INNER JOIN Ad1 ON Ad1.AD1_FILIAL=R.AIJ_FILIAL AND Ad1.AD1_NROPOR=R.AIJ_NROPOR
ORDER BY R.AIJ_NROPOR, R.AIJ_REVISA;
