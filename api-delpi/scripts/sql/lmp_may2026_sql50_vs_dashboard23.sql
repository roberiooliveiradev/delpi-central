-- OVs na SQL simplificada (50) que NÃO aparecem no dashboard API (23) — maio/2026
WITH
StageListing AS (
    SELECT * FROM (VALUES
        ('000002', '000003'), ('000002', '000008'), ('000002', '000012'),
        ('000003', '000003'), ('000003', '000012'), ('000003', '000002'), ('000003', '000008')
    ) AS S(AIJ_PROVEN, AIJ_STAGE)
),
Ad1Active AS (
    SELECT AD1.AD1_FILIAL, AD1.AD1_NROPOR, AD1.AD1_REVISA, AD1.AD1_DESCRI
    FROM AD1010 AD1 WHERE AD1.D_E_L_E_T_ = ''
),
FirstEng AS (
    SELECT A.AIJ_FILIAL, A.AIJ_NROPOR, MIN(A.AIJ_DTINIC) AS first_eng_date
    FROM AIJ010 A
    INNER JOIN Ad1Active AD1 ON AD1.AD1_FILIAL = A.AIJ_FILIAL AND AD1.AD1_NROPOR = A.AIJ_NROPOR
    INNER JOIN StageListing S ON S.AIJ_PROVEN = A.AIJ_PROVEN AND S.AIJ_STAGE = A.AIJ_STAGE
    WHERE A.D_E_L_E_T_ = '' AND ISNULL(A.AIJ_DTINIC, '') <> ''
    GROUP BY A.AIJ_FILIAL, A.AIJ_NROPOR
),
PeriodActivity AS (
    SELECT A.AIJ_FILIAL, A.AIJ_NROPOR
    FROM AIJ010 A
    INNER JOIN Ad1Active AD1 ON AD1.AD1_FILIAL = A.AIJ_FILIAL AND AD1.AD1_NROPOR = A.AIJ_NROPOR
    INNER JOIN StageListing S ON S.AIJ_PROVEN = A.AIJ_PROVEN AND S.AIJ_STAGE = A.AIJ_STAGE
    WHERE A.D_E_L_E_T_ = '' AND A.AIJ_DTINIC BETWEEN '20260501' AND '20260531'
    GROUP BY A.AIJ_FILIAL, A.AIJ_NROPOR
),
AnchorCurrentRev AS (
    SELECT A.AIJ_FILIAL, A.AIJ_NROPOR, A.AIJ_DTINIC AS anchor_start,
        ROW_NUMBER() OVER (PARTITION BY A.AIJ_FILIAL, A.AIJ_NROPOR ORDER BY A.AIJ_DTINIC DESC, A.AIJ_HRINIC DESC, A.R_E_C_N_O_ DESC) AS rn
    FROM AIJ010 A
    INNER JOIN Ad1Active AD1 ON AD1.AD1_FILIAL = A.AIJ_FILIAL AND AD1.AD1_NROPOR = A.AIJ_NROPOR AND AD1.AD1_REVISA = A.AIJ_REVISA
    WHERE A.D_E_L_E_T_ = ''
      AND ((A.AIJ_PROVEN = '000002' AND A.AIJ_STAGE IN ('000003','000012')) OR (A.AIJ_PROVEN = '000003' AND A.AIJ_STAGE IN ('000003','000012')))
),
AnchorChosen AS (SELECT * FROM AnchorCurrentRev WHERE rn = 1),
SqlSimplificada AS (
    SELECT AD1.AD1_NROPOR AS sale_number, RTRIM(AD1.AD1_FILIAL) AS branch, RTRIM(AD1.AD1_DESCRI) AS sale_description, AC.anchor_start
    FROM Ad1Active AD1
    INNER JOIN AnchorChosen AC ON AC.AIJ_FILIAL = AD1.AD1_FILIAL AND AC.AIJ_NROPOR = AD1.AD1_NROPOR
    LEFT JOIN FirstEng FE ON FE.AIJ_FILIAL = AD1.AD1_FILIAL AND FE.AIJ_NROPOR = AD1.AD1_NROPOR
    LEFT JOIN PeriodActivity PA ON PA.AIJ_FILIAL = AD1.AD1_FILIAL AND PA.AIJ_NROPOR = AD1.AD1_NROPOR
    WHERE AC.anchor_start BETWEEN '20260501' AND '20260531'
       OR FE.first_eng_date BETWEEN '20260501' AND '20260531'
       OR PA.AIJ_NROPOR IS NOT NULL
),
Dashboard23 AS (
    SELECT * FROM (VALUES
        ('000054'),('000061'),('000084'),('000087'),('000088'),('000089'),('000090'),('000095'),('000097'),('000102'),
        ('000111'),('000120'),('002871'),('003403'),('003551'),('003561'),('003562'),('003568'),('003571'),
        ('003572'),('003573'),('003574'),('003578')
    ) AS D(sale_number)
)
SELECT S.sale_number, S.branch, S.sale_description, S.anchor_start, 'fora_dashboard' AS motivo
FROM SqlSimplificada S
LEFT JOIN Dashboard23 D ON D.sale_number = S.sale_number
WHERE D.sale_number IS NULL
ORDER BY S.anchor_start, S.sale_number;
