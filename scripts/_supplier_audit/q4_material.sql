SET NOCOUNT ON;
-- physical existence of candidate material/lookup tables
SELECT t.name AS physical, s.X2_NOME, s.X2_MODO
FROM sys.tables t
LEFT JOIN SX2010 s ON s.X2_CHAVE = LEFT(t.name,3)
WHERE t.name IN (
 'SA7010','D2C010','DKI010','D30010','SAD010','AIA010','AIB010','AIC010','CPW010','CPX010',
 'DD1010','DD5010','FTG010','SA6010','SE4010','SED010','SA4010','SYA010','CC2010','CCH010',
 'SX5010','ACJ010','BA4010','COP010','AI5010','SS3010','TBU010','TJW010','SC1010','SC7010',
 'SC8010','SD1010','SF1010','SE2010','SCY010','SF3010','SFT010','SA1010','SRA010','SA3010',
 'AH1010','SU6010','SA8010','SA9010','SE8010','SYS_USR','ZZA010','ZEY010')
ORDER BY t.name;

-- SM0 companies
SELECT 'SM0' s, M0_CODIGO, M0_CODFIL, M0_NOME, M0_NOMECOM, M0_CGC FROM SM0010 WHERE D_E_L_E_T_<>'*' ORDER BY M0_CODIGO, M0_CODFIL;

-- SA2 row counts per company table
SELECT 'SA2010' t, COUNT(*) n FROM SA2010
UNION ALL SELECT 'SA2010_del', COUNT(*) FROM SA2010 WHERE D_E_L_E_T_='*'
UNION ALL SELECT 'SA2030', COUNT(*) FROM SA2030
UNION ALL SELECT 'SA2040', COUNT(*) FROM SA2040
UNION ALL SELECT 'SA2050', COUNT(*) FROM SA2050
UNION ALL SELECT 'SA5010', COUNT(*) FROM SA5010
UNION ALL SELECT 'SA5030', COUNT(*) FROM SA5030
UNION ALL SELECT 'SA5040', COUNT(*) FROM SA5040
UNION ALL SELECT 'SA5050', COUNT(*) FROM SA5050;

-- X2_MODO of SA2 per company dictionary
SELECT 'SX2010' d, X2_MODO, X2_MODOUN, X2_MODOEMP FROM SX2010 WHERE X2_CHAVE='SA2'
UNION ALL SELECT 'SX2030', X2_MODO, X2_MODOUN, X2_MODOEMP FROM SX2030 WHERE X2_CHAVE='SA2'
UNION ALL SELECT 'SX2040', X2_MODO, X2_MODOUN, X2_MODOEMP FROM SX2040 WHERE X2_CHAVE='SA2'
UNION ALL SELECT 'SX2050', X2_MODO, X2_MODOUN, X2_MODOEMP FROM SX2050 WHERE X2_CHAVE='SA2';
