SET NOCOUNT ON;
-- === SA2010 profile (empresa 01, active records) ===
SELECT 'total_active' k, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*';
SELECT 'filial_dist' k, A2_FILIAL d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_FILIAL ORDER BY 3 DESC;
SELECT 'loja_dist' k, A2_LOJA d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_LOJA ORDER BY 3 DESC;
SELECT 'tipo_dist' k, A2_TIPO d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_TIPO;
SELECT 'msblql_dist' k, A2_MSBLQL d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_MSBLQL;
SELECT 'status_dist' k, A2_STATUS d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_STATUS;
SELECT 'tpessoa_dist' k, A2_TPESSOA d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_TPESSOA;
SELECT 'est_top' k, A2_EST d, COUNT(*) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_EST ORDER BY 3 DESC;

-- fill rates for candidate-required fields (blank or null counted)
