  ('A2_END',CONVERT(VARCHAR(60),A2_END)),('A2_BAIRRO',CONVERT(VARCHAR(60),A2_BAIRRO)),
  ('A2_MUN',CONVERT(VARCHAR(60),A2_MUN)),('A2_EST',CONVERT(VARCHAR(60),A2_EST)),
  ('A2_CEP',CONVERT(VARCHAR(60),A2_CEP)),('A2_COD_MUN',CONVERT(VARCHAR(60),A2_COD_MUN)),
  ('A2_DDD',CONVERT(VARCHAR(60),A2_DDD)),('A2_TEL',CONVERT(VARCHAR(60),A2_TEL)),
  ('A2_EMAIL',CONVERT(VARCHAR(60),A2_EMAIL)),('A2_CONTATO',CONVERT(VARCHAR(60),A2_CONTATO)),
  ('A2_BANCO',CONVERT(VARCHAR(60),A2_BANCO)),('A2_AGENCIA',CONVERT(VARCHAR(60),A2_AGENCIA)),
  ('A2_NUMCON',CONVERT(VARCHAR(60),A2_NUMCON)),('A2_COND',CONVERT(VARCHAR(60),A2_COND)),
  ('A2_NATUREZ',CONVERT(VARCHAR(60),A2_NATUREZ)),('A2_CONTA',CONVERT(VARCHAR(60),A2_CONTA)),
  ('A2_GRUPO',CONVERT(VARCHAR(60),A2_GRUPO)),('A2_PAIS',CONVERT(VARCHAR(60),A2_PAIS)),
