-- duplicates analysis
SELECT 'dup_cgc' k, COUNT(*) v FROM (
  SELECT A2_CGC FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' AND LTRIM(RTRIM(A2_CGC))<>''
  GROUP BY A2_CGC HAVING COUNT(*)>1) d;
SELECT 'dup_cod' k, COUNT(*) v FROM (
  SELECT A2_COD FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*'
  GROUP BY A2_COD HAVING COUNT(*)>1) d;
SELECT 'dup_cod_loja' k, COUNT(*) v FROM (
  SELECT A2_COD, A2_LOJA FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*'
  GROUP BY A2_COD, A2_LOJA HAVING COUNT(*)>1) d;
SELECT 'dup_nome' k, COUNT(*) v FROM (
  SELECT A2_NOME FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' AND LTRIM(RTRIM(A2_NOME))<>''
  GROUP BY A2_NOME HAVING COUNT(*)>1) d;

-- A2_COD pattern / sequence evidence
SELECT 'cod_max' k, MAX(A2_COD) v FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*';
SELECT 'cod_samples' k, A2_COD v, A2_LOJA d FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*'
  AND A2_COD IN (SELECT TOP 8 A2_COD FROM SA2010 WHERE D_E_L_E_T_<>'*' ORDER BY A2_COD DESC) ORDER BY A2_COD DESC;

-- loja semantics: how many suppliers have >1 loja
SELECT 'multi_loja_suppliers' k, COUNT(*) v FROM (
  SELECT A2_COD FROM SA2010 WITH (NOLOCK) WHERE D_E_L_E_T_<>'*' GROUP BY A2_COD HAVING COUNT(*)>1) d;
