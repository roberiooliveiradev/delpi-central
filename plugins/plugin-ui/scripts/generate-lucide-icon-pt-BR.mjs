function capitalizePt(phrase) {
  if (!phrase) return phrase;
  return phrase.charAt(0).toLocaleUpperCase("pt-BR") + phrase.slice(1);
}

function composeLabel(kebab) {
  if (CURATED[kebab]) return CURATED[kebab];
  const parts = kebab.split("-").filter(Boolean);
  const translated = parts.map((part) => {
    if (/^\d+$/.test(part)) return part;
    const w = WORD[part];
    if (!w) {
      throw new Error(`Token sem tradução: "${part}" (ícone "${kebab}")`);
    }
    return w;
  });
  return capitalizePt(translated.join(" "));
}

function main() {
  const kebabs = listKebabs();
  const labels = {};
  const unknownTokens = new Set();

  for (const kebab of kebabs) {
    try {
      labels[kebab] = composeLabel(kebab);
    } catch (err) {
      for (const part of kebab.split("-")) {
        if (!/^\d+$/.test(part) && !WORD[part] && !CURATED[kebab]) {
          unknownTokens.add(part);
        }
      }
      throw err;
    }
  }

  if (unknownTokens.size) {
    console.error("Tokens sem WORD:", [...unknownTokens].sort().join(", "));
    process.exit(1);
  }

  const catalog = {
    $schemaComment:
      "Catálogo pt-BR de rótulos Lucide (kebab-case). Gerado por scripts/generate-lucide-icon-pt-BR.mjs — edite CURATED/WORD no script e regenere.",
    locale: "pt-BR",
    labelCount: Object.keys(labels).length,
    labels,
    aliases: ALIASES,
  };

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, `${JSON.stringify(catalog, null, 2)}\n`);
  console.log(`Wrote ${outPath} (${catalog.labelCount} labels)`);
}

